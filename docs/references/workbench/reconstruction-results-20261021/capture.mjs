import { chromium } from '/data/tzq/DexAgent/workbench/frontend/node_modules/playwright-core/index.mjs';
import { writeFile } from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1512,height:982}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base='http://127.0.0.1:8765';
const job='ceaaa66c82ca4a1f8159e982',run='f4d03b51ffa44c467ffca78b';
const directory='.workbench/previews/reconstruction-results-20261021';
await page.goto(`${base}/runs/${run}?view=workflow&phase=scene&cleanup=${job}`);
const pair=page.getByTestId('reconstruction-mask-pair');
await pair.waitFor();
await page.waitForFunction(()=>[...document.querySelectorAll('[data-testid="reconstruction-mask-pair"] video')].every(v=>v.readyState>=1));
await pair.locator('video').first().evaluate(v=>{v.currentTime=6;});
await page.waitForTimeout(250);
await page.screenshot({path:`${directory}/workflow-stage.png`});
await pair.scrollIntoViewIfNeeded();
await pair.locator('video').first().evaluate(async v=>{await v.play();});
await page.waitForTimeout(800);
await pair.locator('video').first().evaluate(v=>v.pause());
await page.waitForFunction(()=>[...document.querySelectorAll('[data-testid="reconstruction-mask-pair"] video')].every(v=>!v.seeking && v.readyState>=2));
await page.screenshot({path:`${directory}/workflow-comparison.png`});
const metadata=await pair.locator('video').evaluateAll(videos=>videos.map(v=>({src:v.currentSrc,duration:v.duration,readyState:v.readyState,time:v.currentTime})));
await page.setViewportSize({width:390,height:844});
await pair.scrollIntoViewIfNeeded();
await page.screenshot({path:`${directory}/workflow-mobile.png`});
const mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await page.setViewportSize({width:1512,height:982});
await page.goto(`${base}/scenes/separation?job=${job}&run=${run}`);
await page.getByTestId('cleanup-synchronized-review').waitFor();
await page.getByLabel('输入视频').locator('option').nth(1).waitFor({state:'attached'});
await page.screenshot({path:`${directory}/review-desktop.png`});
const result={errors,metadata,mobileOverflow,run,job};
await writeFile(`${directory}/browser.json`,JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
await browser.close();
